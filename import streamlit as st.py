import streamlit as st

# 웹 페이지 제목 설정
st.title("🧬 멘델의 유전 법칙 확률 계산기")
st.write("부모의 유전자형(2자)을 입력하면 자손의 우성/열성 표현형 확률을 계산해 줍니다.")

# 1. 입력 및 글자 수 검사 (Streamlit 스타일 예외 처리)
부모1_입력 = st.text_input("첫 번째 부모의 유전자를 입력하세요 (예: Aa)", value="Aa")
부모2_입력 = st.text_input("두 번째 부모의 유전자를 입력하세요 (예: Aa)", value="Aa")

# 글자 수 조건 확인문
if len(부모1_입력) != 2 or len(부모2_입력) != 2:
    st.error("⚠️ 오류: 부모 유전자형은 반드시 정확히 2자여야 합니다!")
else:
    # 2. 분석 시작 버튼을 누르면 계산 진행
    if st.button("유전 법칙 분석하기"):
        # 입력받은 문자를 리스트로 분리
        부모1_리스트 = [부모1_입력[0], 부모1_입력[1]]
        부모2_리스트 = [부모2_입력[0], 부모2_입력[1]]
        자손_리스트 = []

        우성_개수 = 0
        열성_개수 = 0

        # 반복문 활용 (중첩 반복문으로 4가지 조합 생성)
        for 유전자1 in 부모1_리스트:
            for 유전자2 in 부모2_리스트:
                자손_리스트.append(유전자1 + 유전자2)

        # 조건문 활용 (열성 개수가 2일 때 열성, 아닐 때 우성)
        for 조합 in 자손_리스트:
            소문자_개수 = 0
            for 글자 in 조합:
                if 글자.islower():
                    소문자_개수 += 1

            # 소문자가 정확히 2개(예: aa)일 때만 열성 표현형으로 판단
            if 소문자_개수 == 2:
                열성_개수 += 1
            else:
                우성_개수 += 1

        # 3. 결과 계산
        총_조합수 = len(자손_리스트) if 자손_리스트 else 1
        우성_확률 = (우성_개수 / 총_조합수) * 100
        열성_확률 = (열성_개수 / 총_조합수) * 100

        # 4. Streamlit 화면에 결과 출력
        st.success("✅ 분석이 완료되었습니다!")
        st.subheader("📊 유전 법칙 분석 결과")
        st.info(f"생성된 자손 유전자 종류: {', '.join(자손_리스트)}")

        # 보기 좋게 두 칸으로 나누어 결과 보여주기
        col1, col2 = st.columns(2)
        with col1:
            st.metric(label="🔴 우성 표현형 확률", value=f"{우성_확률:.2f}%")
        with col2:
            st.metric(label="🔵 열성 표현형 확률", value=f"{열성_확률:.2f}%")
                                                                                                                                                                                                                                                                                                                                                                                                                            